import { chromium, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const errors = [], messages = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/whatsapp\.(?:net|com)|graph\.facebook\.com/.test(new URL(request.url()).hostname)) messages.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem('chat-settings', JSON.stringify({ version: 0, state: { settings: { onboardingDone: true, language: 'pt-BR' } } })))
  await page.goto('http://127.0.0.1:5274/')
  await page.locator('aside').getByRole('button', { name: 'Habilidades', exact: true }).click()
  await page.getByRole('tab', { name: 'Conectores', exact: true }).click()
  const panel = page.getByTestId('meta-whatsapp-connector')
  await panel.locator('summary').click()
  await panel.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await expect(panel.getByLabel('Token de acesso da Meta', { exact: true })).toBeDisabled()
  await expect(panel.getByLabel('Chave secreta do aplicativo Meta', { exact: true })).toBeDisabled()
  await expect(panel.getByRole('button', { name: 'Gerar token de verificação', exact: true })).toBeDisabled()
  await expect(panel.getByRole('button', { name: 'Verificar e salvar', exact: true })).toBeDisabled()
  await expect(panel.getByText(/Nenhum túnel, hospedagem ou serviço externo é criado automaticamente/)).toBeVisible()
  await expect(panel.getByText(/janela de atendimento de 24 horas/)).toBeVisible()
  await expect(page.getByTestId('telegram-connector')).toBeVisible()
  await expect(page.getByTestId('whatsapp-connector')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Conectores MCP', exact: true })).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/24-whatsapp-meta-credenciais.png', import.meta.url)), fullPage: true })
  await panel.getByRole('region', { name: 'Configuração do webhook da Meta', exact: true }).evaluate(element => element.scrollIntoView({ block: 'start' }))
  await expect(panel.getByRole('button', { name: 'Ativar receptor', exact: true })).toBeDisabled()
  await expect(panel.getByRole('checkbox')).not.toBeChecked()
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/25-whatsapp-meta-webhook.png', import.meta.url)), fullPage: true })
  await page.setViewportSize({ width: 600, height: 1000 })
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 600)
  await expect(panel.getByLabel('URL pública do webhook', { exact: true })).toBeDisabled()
  expect(errors).toEqual([]); expect(messages).toEqual([])
  console.log(JSON.stringify({ portuguese: true, desktopOnly: true, noCredentialCollection: true, noExternalServicesCreated: true, reviewByDefault: true, otherConnectorsPreserved: true, compact: true, noMetaRequests: true }))
} finally { await browser.close() }
