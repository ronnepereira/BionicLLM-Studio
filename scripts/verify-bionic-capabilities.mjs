// Browser verification uses a temporary profile, never the installed LU's data.
import { chromium, expect } from '@playwright/test'
import { readFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const catalog = JSON.parse(readFileSync(new URL('../src/lib/locales/pt-BR.json', import.meta.url), 'utf8'))
const t = (source, params = {}) => (catalog[source] ?? source).replace(/\{(v\d+)\}/g, (_, key) => String(params[key]))
const output = new URL('../docs/bionic-preview/', import.meta.url)
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const forbidden = [], errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.hostname.endsWith('supabase.co') || (url.hostname === 'lu-labs.ai' && /^\/api\//.test(url.pathname)) || (url.hostname === 'api.github.com' && /PurpleDoubleD\/locally-uncensored\/releases/i.test(url.pathname))) forbidden.push(url.origin + url.pathname)
  })
  await page.addInitScript(() => {
    if (localStorage.getItem('bionic-capabilities-seeded')) return
    localStorage.setItem('chat-settings', JSON.stringify({ version: 0, state: { settings: { onboardingDone: true, language: 'pt-BR', appMode: 'cloud', cloudTeasersEnabled: true } } }))
    localStorage.setItem('bionic-capabilities-seeded', 'true')
  })
  const nav = () => page.locator('header').first()
  const gotoSkills = async () => {
    await page.locator('aside').getByRole('button', { name: 'Habilidades', exact: true }).click()
    await page.getByRole('heading', { name: t('Skills and integrations') }).waitFor()
  }
  await page.goto('http://127.0.0.1:5274/')
  await nav().getByRole('button', { name: 'Configurações', exact: true }).waitFor()
  await expect(nav().getByRole('switch')).toHaveCount(0)
  await gotoSkills()
  const template = t('Code review')
  await page.getByRole('button', { name: t('Install {v0}', { v0: template }), exact: true }).click()
  const activate = page.getByRole('switch', { name: t('Activate {v0}', { v0: template }) })
  await expect(activate).toHaveAttribute('aria-checked', 'false')
  await activate.click()
  await expect(activate).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('button', { name: t('New skill'), exact: true }).click()
  await page.getByLabel(t('Name'), { exact: true }).fill('Minha habilidade de teste')
  await page.getByLabel(t('Instructions'), { exact: true }).fill('Preserve esta instrução exatamente como foi escrita.')
  await page.getByRole('button', { name: t('Save'), exact: true }).click()
  await page.getByLabel(t('Import skill file')).setInputFiles({ name: 'SKILL.md', mimeType: 'text/markdown', buffer: Buffer.from('---\nname: habilidade-importada\n---\nUse as fontes fornecidas pelo usuário.') })
  await expect(page.getByRole('heading', { name: 'habilidade-importada', exact: true })).toBeVisible()
  await page.reload()
  await gotoSkills()
  await expect(page.getByRole('switch', { name: t('Activate {v0}', { v0: template }) })).toHaveAttribute('aria-checked', 'true')
  await expect(page.getByRole('heading', { name: 'Minha habilidade de teste', exact: true })).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('04-habilidades.png', output)), fullPage: true, animations: 'disabled' })
  await page.getByRole('tab', { name: 'Marketplace', exact: true }).click()
  await expect(page.getByText(t('Local catalog: ready-to-install skill templates and libraries found on your PC. Plugins, MCP connectors and registered tools remain available in their own tabs.'))).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('13-marketplace-local.png', output)), fullPage: true, animations: 'disabled' })
  await page.getByRole('tab', { name: t('Plugins'), exact: true }).click()
  await expect(page.getByRole('heading', { name: t('Caveman mode') })).toBeVisible()
  await page.getByRole('tab', { name: t('Connectors'), exact: true }).click()
  await expect(page.getByText(t('Connect services through MCP servers. Configure the command and credentials required by your chosen server.'))).toBeVisible()
  await page.getByRole('tab', { name: t('Tools'), exact: true }).click()
  await expect(page.getByRole('heading', { name: 'web_search', exact: true })).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('05-ferramentas.png', output)), fullPage: true, animations: 'disabled' })
  await nav().getByRole('button', { name: 'Configurações', exact: true }).click()
  await expect(page.getByText('Conta de nuvem LU', { exact: true })).toHaveCount(0)
  await expect(page.locator('input[type="password"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Mecanismos de IA', exact: true }).first().click()
  await page.getByRole('button', { name: t('Add Provider'), exact: true }).click()
  await expect(page.getByText('OpenAI', { exact: true }).last()).toBeVisible()
  await expect(page.getByText('Anthropic', { exact: true }).last()).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('06-provedores.png', output)), fullPage: true, animations: 'disabled' })
  await nav().getByRole('button', { name: 'Criar', exact: true }).click()
  await page.locator('aside').getByRole('button', { name: 'Agentes', exact: true }).click()
  await page.getByRole('heading', { name: t('Dedicated agents'), exact: true }).waitFor()
  await page.getByRole('button', { name: t('New agent'), exact: true }).click()
  await page.getByLabel(t('Agent name'), { exact: true }).fill('Pesquisador de fontes')
  await page.getByLabel(t('Agent instructions'), { exact: true }).fill('Pesquise as fontes fornecidas e informe as referências. Peça confirmação antes de enviar mensagens.')
  await page.getByRole('button', { name: t('Save agent'), exact: true }).click()
  await page.reload()
  await page.locator('aside').getByRole('button', { name: 'Agentes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pesquisador de fontes', exact: true })).toBeVisible()
  await page.getByRole('button', { name: t('Open conversation with {v0}', { v0: 'Pesquisador de fontes' }), exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Escolha um modelo')
  await page.screenshot({ path: fileURLToPath(new URL('07-agentes.png', output)), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: t('Edit {v0}', { v0: 'Pesquisador de fontes' }), exact: true }).click()
  await page.getByLabel(t('Agent name'), { exact: true }).fill('Pesquisador revisado')
  await page.getByRole('button', { name: t('Save agent'), exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pesquisador revisado', exact: true })).toBeVisible()
  const remove = page.getByRole('button', { name: t('Remove {v0}', { v0: 'Pesquisador revisado' }), exact: true })
  await remove.click()
  await expect(page.getByRole('heading', { name: 'Pesquisador revisado', exact: true })).toBeVisible()
  await remove.click()
  await expect(page.getByRole('heading', { name: 'Pesquisador revisado', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 600, height: 900 })
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 600)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await nav().getByRole('button', { name: 'Modelos', exact: true }).click()
  // Covers the old startup update timer as well as eager catalog/session probes.
  await page.waitForTimeout(5500)
  expect(forbidden, 'No original LU paid-service/auth/update requests').toEqual([])
  expect(errors, 'No uncaught JavaScript errors').toEqual([])
  console.log('Verified skill install/activation/import/persistence, capability tabs and local marketplace, real native tools, external provider options, and no LU account/cloud/update requests.')
} finally {
  await browser.close()
}
