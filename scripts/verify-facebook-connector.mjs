import { chromium, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], metaRequests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/graph\.(?:facebook|instagram)\.com$/.test(new URL(request.url()).hostname)) metaRequests.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem('chat-settings', JSON.stringify({ version: 0, state: { settings: { onboardingDone: true, language: 'pt-BR' } } })))
  await page.goto('http://127.0.0.1:5274/')
  await page.locator('aside').getByRole('button', { name: 'Habilidades', exact: true }).click()
  await page.getByRole('tab', { name: 'Conectores', exact: true }).click()
  const panel = page.getByTestId('facebook-connector')
  await expect(panel).toHaveJSProperty('open', false)
  await panel.locator('summary').click()
  for (const label of ['ID da Página do Facebook', 'ID do aplicativo Meta', 'Chave secreta do aplicativo Meta', 'Token de acesso da Página']) await expect(panel.getByLabel(label, { exact: true })).toBeDisabled()
  await expect(panel.getByRole('switch')).toBeDisabled()
  await expect(panel.getByRole('switch')).not.toBeChecked()
  await expect(panel.getByText(/A publicação no perfil pessoal do Facebook não está disponível/)).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Verificar e salvar', exact: true })).toBeDisabled()
  await panel.locator('summary').scrollIntoViewIfNeeded()
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/31-facebook-paginas.png', import.meta.url)), fullPage: true })
  await page.setViewportSize({ width: 600, height: 1000 })
  const review = panel.getByRole('region', { name: 'Publicações do Facebook para revisar', exact: true })
  await review.scrollIntoViewIfNeeded()
  await expect(review.getByLabel('Texto da publicação', { exact: true })).toBeDisabled()
  await expect(review.getByRole('button', { name: 'Preparar rascunho local', exact: true })).toBeDisabled()
  await expect(review.getByText('Nenhum rascunho local do Facebook.', { exact: true })).toBeVisible()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 600)
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/32-facebook-revisao-compacto.png', import.meta.url)), fullPage: true })
  await panel.locator('summary').click()
  for (const id of ['google-connector', 'telegram-connector', 'whatsapp-connector', 'meta-whatsapp-connector', 'mcp-connectors']) await expect(page.getByTestId(id)).toBeVisible()
  expect(errors).toEqual([]); expect(metaRequests).toEqual([])
  console.log(JSON.stringify({ portuguese: true, collapsed: true, noPersonalProfilePublishing: true, noBrowserSecrets: true, mandatoryReview: true, compact: true, noMetaRequests: true }))
} finally { await browser.close() }
