import { chromium, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/(^|\.)(youtube\.com|googleapis\.com|google\.com)$/.test(new URL(request.url()).hostname)) requests.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem('chat-settings', JSON.stringify({ version: 0, state: { settings: { onboardingDone: true, language: 'pt-BR' } } })))
  await page.goto('http://127.0.0.1:5274/')
  await page.locator('aside').getByRole('button', { name: 'Habilidades', exact: true }).click()
  await page.getByRole('tab', { name: 'Conectores', exact: true }).click()
  const panel = page.getByTestId('youtube-connector')
  await expect(panel).toHaveJSProperty('open', false)
  await panel.locator('summary').click()
  await expect(panel.getByRole('switch')).not.toBeChecked()
  await expect(panel.getByRole('switch')).toBeDisabled()
  await expect(panel.getByLabel('Solicitar envio de vídeos com revisão obrigatória ao autorizar', { exact: true })).not.toBeChecked()
  await expect(panel.getByRole('button', { name: 'Conectar com Google', exact: true })).toBeDisabled()
  await expect(panel.getByRole('button', { name: 'Selecionar vídeo local', exact: true })).toBeDisabled()
  await panel.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/37-youtube-canal-videos.png', import.meta.url)), fullPage: true })
  const review = panel.getByRole('region', { name: 'Envios do YouTube para revisar', exact: true })
  await review.scrollIntoViewIfNeeded()
  for (const label of ['Título do vídeo', 'Descrição do vídeo']) await expect(review.getByRole('textbox', { name: label, exact: true })).toBeDisabled()
  for (const label of ['Vídeo para enviar', 'Visibilidade solicitada', 'Este vídeo é destinado a crianças?', 'Contém conteúdo realista alterado ou sintético?']) await expect(review.getByRole('combobox', { name: label, exact: true })).toBeDisabled()
  await expect(review.getByRole('combobox', { name: 'Visibilidade solicitada', exact: true })).toHaveValue('private')
  await expect(review.getByRole('combobox', { name: 'Este vídeo é destinado a crianças?', exact: true })).toHaveValue('')
  await expect(review.getByRole('combobox', { name: 'Contém conteúdo realista alterado ou sintético?', exact: true })).toHaveValue('')
  await expect(review.getByText('Nenhum rascunho local do YouTube.', { exact: true })).toBeVisible()
  await expect(review.locator('video,iframe,img')).toHaveCount(0)
  await page.setViewportSize({ width: 600, height: 1000 })
  await review.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 600)
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/38-youtube-revisao-compacto.png', import.meta.url)), fullPage: true })
  expect(errors).toEqual([]); expect(requests).toEqual([])
  console.log(JSON.stringify({ portuguese: true, collapsed: true, nativePickerOnly: true, uploadOptIn: true, privateDefault: true, explicitClassifications: true, compact: true, noGoogleRequests: true }))
} finally { await browser.close() }
