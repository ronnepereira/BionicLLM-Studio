import { chromium, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/(^|\.)linkedin\.com$/.test(new URL(request.url()).hostname)) requests.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem('chat-settings', JSON.stringify({ version: 0, state: { settings: { onboardingDone: true, language: 'pt-BR' } } })))
  await page.goto('http://127.0.0.1:5274/')
  await page.locator('aside').getByRole('button', { name: 'Habilidades', exact: true }).click()
  await page.getByRole('tab', { name: 'Conectores', exact: true }).click()
  const panel = page.getByTestId('linkedin-connector')
  await expect(panel).toHaveJSProperty('open', false)
  await panel.locator('summary').click()
  for (const label of ['ID do aplicativo LinkedIn', 'Chave secreta do aplicativo LinkedIn', 'Token de acesso do usuário LinkedIn']) await expect(panel.getByLabel(label, { exact: true })).toBeDisabled()
  await expect(panel.getByRole('combobox', { name: 'Destino da publicação' })).toBeDisabled()
  await expect(panel.getByRole('switch')).not.toBeChecked()
  await expect(panel.getByRole('switch')).toBeDisabled()
  await expect(panel.getByLabel('Ativar leitura de publicações somente com as permissões concedidas pelo LinkedIn', { exact: true })).not.toBeChecked()
  await panel.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/35-linkedin-perfil-empresa.png', import.meta.url)), fullPage: true })
  const review = panel.getByRole('region', { name: 'Publicações do LinkedIn para revisar', exact: true })
  await review.scrollIntoViewIfNeeded()
  await expect(review.getByRole('textbox')).toBeDisabled()
  await expect(review.getByRole('button', { name: 'Preparar rascunho local', exact: true })).toBeDisabled()
  await expect(review.getByText('Nenhum rascunho local do LinkedIn.', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 600, height: 1000 })
  await review.scrollIntoViewIfNeeded()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 600)
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/36-linkedin-revisao-compacto.png', import.meta.url)), fullPage: true })
  expect(errors).toEqual([]); expect(requests).toEqual([])
  console.log(JSON.stringify({ portuguese: true, collapsed: true, noBrowserSecrets: true, readingOptIn: true, compact: true, noLinkedInRequests: true }))
} finally { await browser.close() }
