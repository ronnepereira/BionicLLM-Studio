import { chromium, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], googleRequests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/googleapis\.com$|accounts\.google\.com$/.test(new URL(request.url()).hostname)) googleRequests.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem('chat-settings', JSON.stringify({ version: 0, state: { settings: { onboardingDone: true, language: 'pt-BR' } } })))
  await page.goto('http://127.0.0.1:5274/')
  await page.locator('aside').getByRole('button', { name: 'Habilidades', exact: true }).click()
  await page.getByRole('tab', { name: 'Conectores', exact: true }).click()
  const panel = page.getByTestId('google-connector')
  await expect(panel).toHaveJSProperty('open', false)
  await panel.locator('summary').click()
  await expect(panel.getByLabel('ID do cliente OAuth do Google', { exact: true })).toBeDisabled()
  await expect(panel.getByLabel('Chave do cliente OAuth do Google', { exact: true })).toBeDisabled()
  await expect(panel.getByText(/exige autorização adicional e confirmação no painel de revisão/)).toBeVisible()
  await expect(panel.getByText(/Nenhum projeto ou conta é criado automaticamente/)).toBeVisible()
  for (const service of ['Gmail', 'Google Drive', 'Google Agenda']) {
    const region = panel.getByRole('region', { name: service, exact: true })
    await expect(region.getByText('Não conectado', { exact: true })).toBeVisible()
    await expect(region.getByRole('button', { name: 'Conectar com Google', exact: true })).toBeDisabled()
    await expect(region.getByRole('switch')).toBeDisabled()
    await expect(region.getByRole('switch')).not.toBeChecked()
  }
  await panel.locator('summary').scrollIntoViewIfNeeded()
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/27-google-conectores.png', import.meta.url)), fullPage: true })
  await page.setViewportSize({ width: 600, height: 1000 })
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 600)
  const actions = panel.getByRole('region', { name: 'Ações do Google para revisar', exact: true })
  await expect(actions.getByRole('combobox', { name: 'Serviço', exact: true })).toBeDisabled()
  await actions.scrollIntoViewIfNeeded()
  await expect(actions.getByRole('button', { name: 'Preparar rascunho local', exact: true })).toBeDisabled()
  await expect(actions.getByLabel('E-mail do destinatário', { exact: true })).toBeDisabled()
  await expect(actions.getByText(/Nada é enviado ou criado no Google até você revisar e confirmar aqui/)).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/30-google-acoes-compacto.png', import.meta.url)), fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await actions.scrollIntoViewIfNeeded()
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/29-google-acoes-revisao.png', import.meta.url)), fullPage: true })
  await panel.getByRole('region', { name: 'Google Agenda', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/28-google-compacto.png', import.meta.url)), fullPage: true })
  await panel.locator('summary').click()
  await expect(panel).toHaveJSProperty('open', false)
  for (const id of ['telegram-connector', 'whatsapp-connector', 'meta-whatsapp-connector', 'mcp-connectors']) await expect(page.getByTestId(id)).toBeVisible()
  expect(errors).toEqual([]); expect(googleRequests).toEqual([])
  console.log(JSON.stringify({ portuguese: true, collapsedByDefault: true, browserCannotCollectCredentials: true, servicesDisabledByDefault: true, compact: true, noGoogleRequests: true }))
} finally { await browser.close() }
