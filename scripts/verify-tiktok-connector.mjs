import { chromium, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/(^|\.)(tiktokapis\.com|tiktok\.com|tiktokcdn\.com)$/.test(new URL(request.url()).hostname)) requests.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem('chat-settings', JSON.stringify({ version: 0, state: { settings: { onboardingDone: true, language: 'pt-BR' } } })))
  await page.goto('http://127.0.0.1:5274/')
  await page.locator('aside').getByRole('button', { name: 'Habilidades', exact: true }).click()
  await page.getByRole('tab', { name: 'Conectores', exact: true }).click()
  const panel = page.getByTestId('tiktok-connector')
  await expect(panel).toHaveJSProperty('open', false)
  await panel.locator('summary').click()
  for (const label of ['Chave do aplicativo TikTok', 'Segredo do aplicativo TikTok', 'Token de renovação TikTok']) await expect(panel.getByRole('textbox', { name: label, exact: true })).toBeDisabled()
  await expect(panel.getByRole('switch')).not.toBeChecked()
  await expect(panel.getByRole('switch')).toBeDisabled()
  for (const label of ['Habilitar envios revisados para a caixa de entrada ao salvar novas credenciais', 'Habilitar consulta de vídeos públicos ao salvar novas credenciais']) await expect(panel.getByRole('checkbox', { name: label, exact: true })).not.toBeChecked()
  await expect(panel.getByRole('button', { name: 'Selecionar vídeo local', exact: true })).toBeDisabled()
  await expect(panel.getByText(/Você precisa abrir a notificação no TikTok/)).toBeVisible()
  await panel.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/39-tiktok-conta-caixa-entrada.png', import.meta.url)), fullPage: true })
  const review = panel.getByRole('region', { name: 'Envios para a caixa de entrada do TikTok para revisar', exact: true })
  await review.scrollIntoViewIfNeeded()
  await expect(review.getByRole('combobox', { name: 'Vídeo para enviar', exact: true })).toBeDisabled()
  await expect(review.getByRole('textbox', { name: 'Notas locais para edição (não enviadas ao TikTok)', exact: true })).toBeDisabled()
  await expect(review.getByText('Nenhum rascunho local do TikTok.', { exact: true })).toBeVisible()
  await expect(review.locator('video,iframe,img')).toHaveCount(0)
  await page.setViewportSize({ width: 600, height: 1000 })
  await review.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 600)
  await page.screenshot({ path: fileURLToPath(new URL('../docs/bionic-preview/40-tiktok-revisao-compacto.png', import.meta.url)), fullPage: true })
  expect(errors).toEqual([]); expect(requests).toEqual([])
  console.log(JSON.stringify({ portuguese: true, collapsed: true, nativePickerOnly: true, uploadAndReadingOptIn: true, inboxCompletionExplicit: true, compact: true, noTikTokRequests: true }))
} finally { await browser.close() }
